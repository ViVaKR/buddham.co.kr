import { EnvironmentProviders, Provider, Type } from "@angular/core";
import { Data, RedirectFunction, Resolve, ResolveData, ResolveFn, Routes, UrlMatcher } from "@angular/router";
import { Observable } from "rxjs";

interface Route {
  // ────────────────────────────────────────────────────────
  // 1. 핵심 매칭 속성 (주소창 관련)
  // ────────────────────────────────────────────────────────
  /** 매칭할 URL 경로 (예: 'sutra', 'auth/:id') */
  path?: string;

  /** 'full'(완전 일치) 또는 'prefix'(앞부분 일치). 빈 패스('')일 때 중요! */
  pathMatch?: 'full' | 'prefix';

  /** URL 매칭 로직을 커스텀하고 싶을 때 쓰는 특수 함수 */
  matcher?: UrlMatcher;

  // ────────────────────────────────────────────────────────
  // 2. 컴포넌트 & 로딩 속성 (화면 표시 관련)
  // ────────────────────────────────────────────────────────
  /** 이 주소로 들어왔을 때 띄울 스탠드얼론 컴포넌트 (Lazy Loading용) */
  loadComponent?: () => Type<any> | Promise<Type<any> | { default: Type<any> }>;

  /** 자식 라우트 파일들을 통째로 지연 로딩할 때 사용 (Lazy Loading용) */
  loadChildren?: () => Type<any> | Promise<any> | Observable<any>;

  /** 전통적인 방식으로, 즉시 로딩할 컴포넌트를 직접 지정 */
  component?: Type<any>;

  /** 이름이 지정된 복수의 <router-outlet>을 쓸 때 컴포넌트들을 매핑 */
  components?: { [key: string]: Type<any> };


  // ────────────────────────────────────────────────────────
  // 3. 리다이렉트 & 포워딩
  // ────────────────────────────────────────────────────────
  /** 특정 주소로 강제 이동시키고 싶을 때 사용 (예: redirectTo: 'home') */
  redirectTo?: string | RedirectFunction;


  // ────────────────────────────────────────────────────────
  // 4. 가드 (Guard) - 접근 제어 및 보안
  // ────────────────────────────────────────────────────────
  /** 이 라우트에 진입할 수 있는지 검사 (예: 로그인 여부 체크) */
  canActivate?: any[];

  /** 이 라우트에서 다른 곳으로 빠져나갈 수 있는지 검사 (예: 작성 중 취소창) */
  canDeactivate?: any[];

  /** 자식 라우트들까지 한방에 진입 제어를 걸고 싶을 때 사용 */
  canActivateChild?: any[];

  /** 지연 로딩(Lazy Loading) 코드를 다운로드하기 전에 권한을 체크할 때 사용 */
  canMatch?: any[];


  // ────────────────────────────────────────────────────────
  // 5. 데이터 주입 & 의존성 (DI)
  // ────────────────────────────────────────────────────────
  /** 컴포넌트에 넘겨줄 정적 데이터나 레이아웃 설정 플래그 (예: { showBar: false }) */
  data?: Data;

  /** 컴포넌트가 뜨기 전에 백엔드 데이터를 미리 받아오고 싶을 때 쓰는 해결사 */
  resolve?: ResolveData;

  /** 🌟 [아까 찾은 보물!] 이 라우트와 자식들 안에서만 살아 숨쉴 서비스/값들을 주입 */
  providers?: EnvironmentProviders | Provider[];


  // ────────────────────────────────────────────────────────
  // 6. 구조적 속성 (계층 관리)
  // ────────────────────────────────────────────────────────
  /** 하위 자식 라우트들을 배열로 정의할 때 사용 */
  children?: Routes;


  // ────────────────────────────────────────────────────────
  // 7. 기타 부가 기능
  // ────────────────────────────────────────────────────────
  /** 브라우저 탭에 표시될 페이지 제목 (문자열 또는 커스텀 타이틀 서비스 클래스) */
  title?: string | Type<Resolve<string>> | ResolveFn<string>;

  /** 라우터 링크가 활성화되었을 때 적용할 CSS 클래스들의 세부 옵션 */
  titleOptions?: { [key: string]: any };
}

